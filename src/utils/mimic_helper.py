def load_diagnoses(data_dir: dir) -> pd.DataFrame:
    """
    Load the diagnostics table and perform cleaning and aggregation/grouping
    
    :param data_dir: data directory, contianing a folder named mimic (with diagnoses data inside)
    :type data_dir: dir
    :return: Dataframe with ICD-9 rows dropped and the rest grouped by hadm_id
    :rtype: DataFrame
    """
    full_dir = data_dir + "/mimic/diagnoses_icd.csv.gz"
    dia = pd.read_csv(full_dir)
    dia = dia[dia['icd_version'] != 9]
    
    # Format ICD-10 codes to proper format (letter + 2 digits . remaining)
    dia['icd_code'] = dia['icd_code'].apply(lambda x: x[:3] + '.' + x[3:] if pd.notna(x) and len(x) > 3 else x)

    dia = dia \
        .dropna() \
        .groupby(['hadm_id', 'subject_id']) \
        .agg(set) \
        .reset_index()

    print(dia.info())
    return dia

