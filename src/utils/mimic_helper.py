#final dataframe: 
def finalize_merged_frames(merged_df: pd.DataFrame, save=False) -> pd.DataFrame:
    """
    Mainly dropping rows, which don't have ICD-10 codes and then clean-up and rearranging of the tables.
    
    :param merged_df: Dataframe generated by the load_and_merge_notes function
    :type merged_df: pd.DataFrame
    :return: Cleaned up dataframe
    :rtype: DataFrame
    """
    finalized_df = merged_df.dropna(subset=['note_id', 'text'])
    cols_to_keep = ['note_id', 'text', 'hadm_id','subject_id', 'icd_code']
    finalized_df = finalized_df[cols_to_keep]
    finalized_df = finalized_df.rename(columns={'note_id': 'report_id', 'text' : 'report_txt', 'icd_code' : 'y_true'})
    finalized_df = finalized_df[['report_id', 'report_txt', 'hadm_id', 'subject_id', 'y_true']]
    return finalized_df 



# notes merge with processed admissions
def load_and_merge_notes(data_dir: dir, dia: pd.DataFrame) -> pd.DataFrame:
    """
    load notes from data directory, process it and merge with admissions dataframes
    :param data_dir: data directory with "mimic" folder inside
    :type data_dir: dir
    :param adm_dia: admissions dataframe with diagnostic codes added and aggregated
    :type adm_dia: pd.DataFrames
    :return: Merged dataframe with notes and diagnoses
    :rtype: DataFrame
    """

    notes = pd.read_csv(data_dir + "/mimic/" + "discharge.csv.gz")
    filtered_notes = filter_notes(notes)
